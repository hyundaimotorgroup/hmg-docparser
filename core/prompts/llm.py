def build_task_prompt_llm(key, value_dict=None, user_prompt=None, *, policy=None):
    from core.prompts.task import TaskPrompt
    from core.services.prompt_policy import DEFAULT_PROMPT_POLICY

    return TaskPrompt.build(
        key,
        _system_llm(key),
        value_dict,
        user_prompt,
        policy=policy or DEFAULT_PROMPT_POLICY,
    )


def get_prompt_llm(key, value_dict=None):
    task = build_task_prompt_llm(key, value_dict)
    return task.system + "\n" + task.user
